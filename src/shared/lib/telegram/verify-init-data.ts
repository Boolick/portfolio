import crypto from "node:crypto";

export interface VerifiedTelegramUser {
  id: number;
  first_name: string;
  last_name?: string;
  username?: string;
  language_code?: string;
  is_premium?: boolean;
  photo_url?: string;
}

export type VerifyInitDataFailureReason =
  | "missing_data"
  | "missing_token"
  | "payload_too_large"
  | "missing_hash"
  | "invalid_hash_format"
  | "hash_mismatch"
  | "missing_auth_date"
  | "future_auth_date"
  | "expired"
  | "invalid_user_json";

export type VerifyInitDataResult =
  | {
      ok: true;
      user?: VerifiedTelegramUser;
      startParam?: string;
      authDate: number;
    }
  | {
      ok: false;
      reason: VerifyInitDataFailureReason;
    };

const HASH_REGEX = /^[0-9a-f]{64}$/i;
const MAX_RAW_LENGTH = 4096;

/**
 * Validates the cryptographic HMAC-SHA256 signature of Telegram WebApp initData.
 * Ensures the payload was generated by Telegram servers using the bot token,
 * has not been tampered with, and is within freshness limits (maxAgeSeconds).
 */
export function verifyTelegramInitData(
  initDataRaw: string | null | undefined,
  botToken: string | null | undefined,
  maxAgeSeconds = 86400,
  nowSeconds = Math.floor(Date.now() / 1000)
): VerifyInitDataResult {
  if (!initDataRaw || typeof initDataRaw !== "string") {
    return { ok: false, reason: "missing_data" };
  }

  if (!botToken || typeof botToken !== "string") {
    return { ok: false, reason: "missing_token" };
  }

  if (initDataRaw.length > MAX_RAW_LENGTH) {
    return { ok: false, reason: "payload_too_large" };
  }

  const params = new URLSearchParams(initDataRaw);
  const hash = params.get("hash");

  if (!hash) {
    return { ok: false, reason: "missing_hash" };
  }

  if (!HASH_REGEX.test(hash)) {
    return { ok: false, reason: "invalid_hash_format" };
  }

  // Telegram data_check_string: all key=value pairs except hash, sorted lexicographically
  const pairs: string[] = [];
  params.forEach((value, key) => {
    if (key !== "hash") {
      pairs.push(`${key}=${value}`);
    }
  });

  pairs.sort();
  const dataCheckString = pairs.join("\n");

  // secret_key = HMAC_SHA256("WebAppData", bot_token)
  const secretKey = crypto.createHmac("sha256", "WebAppData").update(botToken).digest();

  // expected_hash = HMAC_SHA256(secret_key, data_check_string)
  const expectedBuf = crypto.createHmac("sha256", secretKey).update(dataCheckString).digest();
  const actualBuf = Buffer.from(hash, "hex");

  if (
    actualBuf.length !== expectedBuf.length ||
    !crypto.timingSafeEqual(actualBuf, expectedBuf)
  ) {
    return { ok: false, reason: "hash_mismatch" };
  }

  // Validate auth_date freshness
  const authDateStr = params.get("auth_date");
  if (!authDateStr) {
    return { ok: false, reason: "missing_auth_date" };
  }

  const authDate = parseInt(authDateStr, 10);
  if (isNaN(authDate)) {
    return { ok: false, reason: "missing_auth_date" };
  }

  if (authDate - nowSeconds > 60) {
    return { ok: false, reason: "future_auth_date" };
  }

  if (nowSeconds - authDate > maxAgeSeconds) {
    return { ok: false, reason: "expired" };
  }

  // Safely parse user JSON payload if present
  let user: VerifiedTelegramUser | undefined = undefined;
  const userRaw = params.get("user");
  if (userRaw) {
    try {
      const parsed = JSON.parse(userRaw);
      if (
        typeof parsed === "object" &&
        parsed !== null &&
        typeof parsed.id === "number" &&
        typeof parsed.first_name === "string"
      ) {
        user = {
          id: parsed.id,
          first_name: parsed.first_name,
          last_name: typeof parsed.last_name === "string" ? parsed.last_name : undefined,
          username: typeof parsed.username === "string" ? parsed.username : undefined,
          language_code:
            typeof parsed.language_code === "string" ? parsed.language_code : undefined,
          is_premium:
            typeof parsed.is_premium === "boolean" ? parsed.is_premium : undefined,
          photo_url: typeof parsed.photo_url === "string" ? parsed.photo_url : undefined,
        };
      } else {
        return { ok: false, reason: "invalid_user_json" };
      }
    } catch {
      return { ok: false, reason: "invalid_user_json" };
    }
  }

  const startParam = params.get("start_param") ?? undefined;

  return {
    ok: true,
    user,
    startParam,
    authDate,
  };
}
